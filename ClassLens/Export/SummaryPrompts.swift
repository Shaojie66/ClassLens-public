import Foundation

/// Prompts for the after-class summary. The vault's rules (AI协作规则 §3–4) forbid inventing formulas,
/// numbers or assessment details, so the model works only from the transcript and slides and cites times.
enum SummaryPrompts {
    static let system = """
    你在帮一名中国学生整理一节英文授课的大学课程（计算机、统计、数据科学方向）的课后总结。材料是这节课的机器转写（英文，有识别错误）、课件文字和课上的提问。

    用中文写 Markdown，按下面的结构，二级标题照抄：
    ## 核心脉络
    三到五句话说清这节课从哪里讲到哪里、主线是什么。
    ## 分节要点
    按讲课顺序分成几节，每节用三级标题，下面列要点。每个要点后面标出处，例如 `[12:34]` 或 `[12:34, 课件第 14 页]`。
    ## 新术语
    表格：| 英文 | 中文 | 一句话含义 |，只列这节课实际讲到的术语。
    ## 老师特别强调的内容
    老师明确说“重要”“要注意”“常见错误”“会考”之类的地方，原样标出时间；没有就写“转写中没有明确的强调”。
    ## 课上提问回顾
    老师向全班提的问题和要点，标时间。
    ## 待核对
    每条写明时间、转写原文、你的推断和理由。包括：所有推断出来的数字（见下面的数字规则）、听不清或可能识别错的关键术语、你不确定的地方。

    数字规则（最重要，凡是推断出来的数字一律放进“待核对”）：
    - 正文（“待核对”以外的部分）只能写在转写或课件里原样出现过的数字。转写里的英文数词照字面换算就算原样出现，例如 "fifteen" 是 15、"zero point zero five" 是 0.05。
    - 下面这些都算推断出来的数字：把听错的数字改成你认为老师想说的（例如转写是 "fifteen"，你觉得应该是 50）；自己算出来的结果；几处说法不一致时挑了其中一个；转写里没有、按上下文补上的。
    - 推断出来的数字不能在正文里写成确定的结论。正文里写转写原文的数字，并注明“（待核对）”，或者不写具体数值；然后在“待核对”里列一条，写明时间、转写原文、你的推断和理由。
    - 同一个量在转写里前后说法不一致（例如前面说 n 是 thirty，后面念代码时转写成 thirteen），或者转写和课件对不上时，正文不替老师选，两个都写进“待核对”。英文 -teen 和 -ty（fifteen / fifty）最容易听混，见到要特别留意。
    - “待核对”只列需要核对的条目；原样出现、前后一致的数字不要列进去，也不要写“应无问题”之类的条目。每条一两句话。

    硬性要求：
    - 只依据给你的转写、课件和提问，不补充材料里没有的知识、公式、数字、作业或考试信息。
    - 转写有识别错误：按课件和上下文推断原意，推断出来的写进“待核对”。
    - 公式用 LaTeX（行内 $...$）；术语第一次出现附英文。
    - 不要写 frontmatter，不要写一级标题，不要写开场白。
    """

    static func user(transcript: String, slides: String, questions: String) -> String {
        """
        课件（每页的文字，按页码）：
        \(slides.isEmpty ? "（这节课没有打开课件）" : slides)

        课上的提问：
        \(questions.isEmpty ? "（没有记录到提问）" : questions)

        转写（[时间] (课件页) 英文原文）：
        \(transcript)
        """
    }
}
